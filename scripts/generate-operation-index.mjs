#!/usr/bin/env node
/**
 * Generate `src/generated/operation-index.ts` from `spec/openapi.json`.
 *
 * openapi-typescript emits the *type-level* `operations` map (compile-time
 * only). The typed client needs the same operation set at RUNTIME — the
 * HTTP verb and URL template for every `operationId` — so it can build one
 * dispatchable method per operation. This script produces that runtime
 * mirror.
 *
 * It is deliberately committed under `src/generated/` so:
 *   1. the drift check (`npm run types:check`) regenerates it alongside the
 *      types and fails on any un-committed diff, and
 *   2. the operation set stays byte-for-byte in lock-step with the spec that
 *      produced `api-types.ts`.
 *
 * The key set here is asserted equal to the `operations` interface key set by
 * `src/__tests__/contract/spec-coverage.contract.test.ts`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HTTP_METHODS = ['get', 'put', 'post', 'delete', 'patch', 'head', 'options'];

const here = dirname(fileURLToPath(import.meta.url));
const sdkRoot = resolve(here, '..');
const specPath = resolve(sdkRoot, 'spec/openapi.json');
const outPath = resolve(sdkRoot, 'src/generated/operation-index.ts');

const spec = JSON.parse(readFileSync(specPath, 'utf8'));

/** @type {Array<{ id: string, method: string, path: string, hasPathParams: boolean, hasBody: boolean }>} */
const entries = [];
for (const [path, item] of Object.entries(spec.paths ?? {})) {
  for (const method of HTTP_METHODS) {
    const op = item[method];
    if (!op || typeof op !== 'object' || !op.operationId) continue;
    entries.push({
      id: op.operationId,
      method: method.toUpperCase(),
      path,
      hasPathParams: /\{[^}]+\}/.test(path),
      hasBody: Boolean(op.requestBody),
    });
  }
}

// Stable ordering: sort by operationId so the generated file is deterministic
// regardless of object-key iteration order in the source spec.
entries.sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));

const seen = new Set();
for (const e of entries) {
  if (seen.has(e.id)) {
    throw new Error(`Duplicate operationId in spec/openapi.json: ${e.id}`);
  }
  seen.add(e.id);
}

const lines = [];
lines.push('/**');
lines.push(' * This file was auto-generated by scripts/generate-operation-index.mjs.');
lines.push(' * Do not make direct changes to the file. Run `npm run generate:types`');
lines.push(' * (or `npm run types:check`) to regenerate it from spec/openapi.json.');
lines.push(' *');
lines.push(' * Runtime mirror of the compile-time `operations` map in `api-types.ts`:');
lines.push(' * the HTTP verb + URL template for every operationId, used by the typed');
lines.push(' * client to build one dispatchable method per operation.');
lines.push(' */');
lines.push('');
lines.push('export interface OperationMeta {');
lines.push('  /** HTTP verb, upper-cased. */');
lines.push('  readonly method: string;');
lines.push('  /** URL template, e.g. `/api/items/{item}` (path params in braces). */');
lines.push('  readonly path: string;');
lines.push('  /** True when `path` contains at least one `{param}` placeholder. */');
lines.push('  readonly hasPathParams: boolean;');
lines.push('  /** True when the operation declares a request body. */');
lines.push('  readonly hasBody: boolean;');
lines.push('}');
lines.push('');
lines.push('export const operationIndex = {');
for (const e of entries) {
  lines.push(
    `  ${JSON.stringify(e.id)}: { method: ${JSON.stringify(e.method)}, `
      + `path: ${JSON.stringify(e.path)}, `
      + `hasPathParams: ${e.hasPathParams}, hasBody: ${e.hasBody} },`,
  );
}
lines.push('} as const satisfies Record<string, OperationMeta>;');
lines.push('');
lines.push('/** Every operationId known to the runtime client (spec-derived). */');
lines.push('export type GeneratedOperationId = keyof typeof operationIndex;');
lines.push('');

writeFileSync(outPath, lines.join('\n'));
// eslint-disable-next-line no-console
console.log(`operation-index.ts → ${entries.length} operations`);
